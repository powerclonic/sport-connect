const storedLocale = typeof window === 'undefined' ? null : window.localStorage.getItem(localeStorageKey)
const i18n = createI18n({
  legacy: false,
  locale: storedLocale === 'pt-BR' || storedLocale === 'en' ? storedLocale : 'en',
  fallbackLocale: 'en',
  messages,
})

export function setLocale (nextLocale: SupportedLocale) {
  i18n.global.locale.value = nextLocale

  if (typeof window !== 'undefined') {
    window.localStorage.setItem(localeStorageKey, nextLocale)
    window.document.documentElement.lang = nextLocale
  }
}

export default i18n
